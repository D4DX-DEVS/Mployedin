// ── Merge into en.json and ar.json ────────────────────────────────────

let enAdded = 0;
let arAdded = 0;

for (const [ns, translations] of Object.entries(newTranslations)) {
  if (!en[ns]) {
    en[ns] = translations.en;
    enAdded += Object.keys(translations.en).length;
  } else {
    // Merge only missing keys
    for (const [key, val] of Object.entries(translations.en)) {
      if (!(key in en[ns])) {
        en[ns][key] = val;
        enAdded++;
      }
    }
  }

  if (!ar[ns]) {
    ar[ns] = translations.ar;
    arAdded += Object.keys(translations.ar).length;
  } else {
    for (const [key, val] of Object.entries(translations.ar)) {
      if (!(key in ar[ns])) {
        ar[ns][key] = val;
        arAdded++;
      }
    }
  }
}

fs.writeFileSync(enPath, JSON.stringify(en, null, 2) + "\n", "utf8");
fs.writeFileSync(arPath, JSON.stringify(ar, null, 2) + "\n", "utf8");

console.log(`✅ Added ${enAdded} keys to en.json`);
console.log(`✅ Added ${arAdded} keys to ar.json`);
